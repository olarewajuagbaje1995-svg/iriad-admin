export type ReportPDFData = {
  orgName: string
  reportType: 'Weekly' | 'Monthly'
  period: string
  staffName: string
  staffRole: string
  activities: string
  tasks: string
  meetings: string
  achievements: string
  challenges: string
  outstanding: string
  nextPlan: string
  status: string
  submittedAt: string
  generatedAt: string
}

/**
 * Generates a print-friendly PDF report for a submitted report.
 * Opens a new window with print styles; user can "Save as PDF" from the print dialog.
 * No external dependencies required.
 */
export function generateReportPDF(data: ReportPDFData) {
  const printHtml = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${data.reportType} Report - ${data.period}</title>
  <style>
    @page { margin: 18mm; }
    * { box-sizing: border-box; }
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, 'Helvetica Neue', Arial, sans-serif;
      font-size: 11pt;
      color: #1f2937;
      line-height: 1.5;
      margin: 0;
      padding: 0;
    }
    .no-print { display: none; }
    .header {
      border-bottom: 3px solid #0274be;
      padding-bottom: 16px;
      margin-bottom: 24px;
    }
    .header h1 {
      margin: 0;
      font-size: 20pt;
      color: #0274be;
    }
    .header p { margin: 4px 0 0; color: #6b7280; }
    .meta {
      display: grid;
      grid-template-columns: 1fr 1fr;
      gap: 16px 24px;
      margin-bottom: 24px;
      font-size: 9.5pt;
      color: #4b5563;
    }
    .meta div { margin-bottom: 4px; }
    .meta .label { font-weight: 600; color: #0274be; }
    .section { margin-bottom: 20px; }
    .section h2 {
      font-size: 11pt;
      color: #0274be;
      border-bottom: 1px solid #e5e7eb;
      padding-bottom: 4px;
      margin: 0 0 8px 0;
      text-transform: uppercase;
      letter-spacing: 0.05em;
    }
    .section p {
      margin: 0;
      white-space: pre-wrap;
      background: #f9fafb;
      padding: 10px 14px;
      border-radius: 6px;
      border: 1px solid #e5e7eb;
    }
    .section p.empty { color: #9ca3af; font-style: italic; }
    .status-badge {
      display: inline-block;
      padding: 4px 10px;
      border-radius: 4px;
      font-size: 8.5pt;
      font-weight: 600;
      text-transform: uppercase;
      letter-spacing: 0.05em;
    }
    .status-approved { background: #dcfce7; color: #166534; }
    .status-submitted { background: #dbeafe; color: #1e40af; }
    .status-draft { background: #f3f4f6; color: #4b5563; }
    .status-revision_requested { background: #fef3c7; color: #92400e; }
    .status-rejected { background: #fee2e2; color: #991b1b; }
    .footer {
      margin-top: 32px;
      padding-top: 16px;
      border-top: 1px solid #e5e7eb;
      font-size: 8pt;
      color: #9ca3af;
      text-align: center;
    }
    @media print {
      body { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
      .no-print { display: none !important; }
    }
  </style>
</head>
<body>
  <div class="header">
    <h1>${data.orgName}</h1>
    <p>${data.reportType} Report &bull; ${data.period}</p>
  </div>

  <div class="meta">
    <div><span class="label">Staff:</span> ${data.staffName}</div>
    <div><span class="label">Role:</span> ${data.staffRole}</div>
    <div><span class="label">Period:</span> ${data.period}</div>
    <div><span class="label">Status:</span>
      <span class="status-badge status-${data.status.toLowerCase().replace(' ', '_')}">${data.status}</span>
    </div>
    <div><span class="label">Submitted:</span> ${data.submittedAt}</div>
    <div><span class="label">Generated:</span> ${data.generatedAt}</div>
  </div>

  <div class="section">
    <h2>Activities Carried Out</h2>
    <p class="${!data.activities ? 'empty' : ''}">${data.activities || '—'}</p>
  </div>
  <div class="section">
    <h2>Tasks Completed</h2>
    <p class="${!data.tasks ? 'empty' : ''}">${data.tasks || '—'}</p>
  </div>
  <div class="section">
    <h2>Meetings Attended</h2>
    <p class="${!data.meetings ? 'empty' : ''}">${data.meetings || '—'}</p>
  </div>
  <div class="section">
    <h2>Achievements &amp; Outcomes</h2>
    <p class="${!data.achievements ? 'empty' : ''}">${data.achievements || '—'}</p>
  </div>
  <div class="section">
    <h2>Challenges</h2>
    <p class="${!data.challenges ? 'empty' : ''}">${data.challenges || '—'}</p>
  </div>
  <div class="section">
    <h2>Outstanding Activities</h2>
    <p class="${!data.outstanding ? 'empty' : ''}">${data.outstanding || '—'}</p>
  </div>
  <div class="section">
    <h2>Next Period Plan</h2>
    <p class="${!data.nextPlan ? 'empty' : ''}">${data.nextPlan || '—'}</p>
  </div>

  <div class="footer">
    Generated by ${data.orgName} Operations Management System &bull;
    ${data.generatedAt}
  </div>

  <button class="no-print" onclick="window.print()" style="
    position: fixed; bottom: 20px; right: 20px;
    background: #0274be; color: #fff; border: none;
    padding: 10px 20px; border-radius: 6px; font-weight: 600;
    cursor: pointer; box-shadow: 0 2px 8px rgba(0,0,0,0.15);
  ">
    Print / Save as PDF
  </button>
  <script>window.print();</script>
</body>
</html>
  `

  const win = window.open('', '_blank', 'width=800,height=900')
  if (!win) {
    // Fallback: create a hidden iframe and print
    const iframe = document.createElement('iframe')
    iframe.style.position = 'absolute'
    iframe.style.width = '0'
    iframe.style.height = '0'
    iframe.style.border = 'none'
    document.body.appendChild(iframe)
    const doc = iframe.contentDocument || iframe.contentWindow?.document
    if (doc) {
      doc.open()
      doc.write(printHtml)
      doc.close()
      setTimeout(() => {
        iframe.contentWindow?.focus()
        iframe.contentWindow?.print()
        document.body.removeChild(iframe)
      }, 250)
    }
    return
  }

  win.document.open()
  win.document.write(printHtml)
  win.document.close()
  setTimeout(() => win.print(), 250)
}
